#!/usr/bin/env node

/**
 * Fix TypeScript path aliases for Coolify deployment
 * This script runs after npm install to ensure path aliases work at runtime
 */

const fs = require('fs');
const path = require('path');

console.log('🔧 Fixing TypeScript path aliases for Coolify...');

// Create module-alias configuration
const moduleAliasConfig = {
  "_moduleAliases": {
    "@shared": "./shared",
    "@": "./client/src"
  }
};

// Add module-alias to package.json
const packageJsonPath = path.join(__dirname, '..', 'package.json');
const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));

// Merge module aliases
packageJson._moduleAliases = {
  ...packageJson._moduleAliases,
  ...moduleAliasConfig._moduleAliases
};

// Write updated package.json
fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2) + '\n');

// Create a runtime resolver file
const resolverContent = `
// Auto-generated by fix-path-aliases.js
// This file ensures path aliases work at runtime
require('module-alias/register');

// Additional path resolution for TypeScript
const Module = require('module');
const originalResolveFilename = Module._resolveFilename;

Module._resolveFilename = function (request, parent, isMain) {
  // Handle @shared/* imports
  if (request.startsWith('@shared/')) {
    request = request.replace('@shared/', __dirname + '/../shared/');
  }
  // Handle @/* imports
  if (request.startsWith('@/')) {
    request = request.replace('@/', __dirname + '/../client/src/');
  }
  
  return originalResolveFilename.call(this, request, parent, isMain);
};
`;

// Write resolver file
const resolverPath = path.join(__dirname, '..', 'path-resolver.js');
fs.writeFileSync(resolverPath, resolverContent);

console.log('✅ Path aliases fixed!');
console.log('📝 Added _moduleAliases to package.json');
console.log('📝 Created path-resolver.js');
console.log('');
console.log('🚀 To use in your server files, add this at the top:');
console.log("   require('./path-resolver');");